def render_message(text, kind="tip"):
    """Show a friendly message instead of a technical error."""
    css_class = "friendly-note" if kind == "note" else "friendly-tip"
    st.markdown(f'<div class="{css_class}">{text}</div>', unsafe_allow_html=True)


def render_progress(placeholder, progress_bar, emoji, message, percent):
    """Show one child-friendly step of the magic while the models work."""
    placeholder.markdown(
        f"""
        <div class="magic-step">
            <span class="magic-emoji">{emoji}</span>
            <div class="magic-text">{message}</div>
        </div>
        """,
        unsafe_allow_html=True,
    )
    progress_bar.progress(percent)


def render_story(story):
    """Show the finished story inside a storybook page."""
    safe_story = html.escape(story)
    st.markdown(
        f"""
        <div class="story-card">
            <div class="story-title">🌟 Your Story 🌟</div>
            <div class="story-text">{safe_story}</div>
            <div class="story-end">～ The End ～</div>
        </div>
        """,
        unsafe_allow_html=True,
    )


def render_audio(audio_bytes):
    """Show the narration section so the child can listen to the story."""
    st.markdown(
        """
        <div class="audio-card">
            <div class="audio-title">🎧 Listen to your story</div>
            <div class="audio-hint">Press play and I will read it to you!</div>
        </div>
        """,
        unsafe_allow_html=True,
    )
    st.audio(audio_bytes, format="audio/wav")


def reset_story():
    """Forget the current story so the child can start a new adventure."""
    st.session_state.pop("story", None)
    st.session_state.pop("audio_bytes", None)


# ---------------------------------------------------------------------------
# 6. Main application
# ---------------------------------------------------------------------------

def main():
    """
    Run the complete storytelling application.

    main() is the orchestrator: it prepares the page, collects the picture
    from the child, calls the three AI stages in order, and presents the
    story and its narration.
    """
    # --- Page setup ------------------------------------------------------
    st.set_page_config(
        page_title="Magic Story Maker",
        page_icon="🎈",
        layout="centered",
    )
    apply_styles()
    render_header()

    # --- Step 1: the child chooses a picture -----------------------------
    st.markdown('<div class="section-title">🖼️ Choose your picture</div>', unsafe_allow_html=True)

    uploaded_file = st.file_uploader(
        "Pick a happy picture from your computer",
        type=ACCEPTED_IMAGE_TYPES,
        on_change=reset_story,
    )

    if uploaded_file is None:
        render_message("👆 Choose a picture and the magic will begin!")
        st.markdown(
            '<div class="footer-note">Made with ✨ for young storytellers</div>',
            unsafe_allow_html=True,
        )
        return

    # --- Step 2: open and preview the picture ----------------------------
    try:
        image = Image.open(uploaded_file).convert("RGB")
    except (UnidentifiedImageError, OSError, ValueError):
        render_message(
            "😅 Oh no! I could not open that picture. Please try a different one.",
            kind="note",
        )
        return

    left, middle, right = st.columns([1, 3, 1])
    with middle:
        st.image(image, use_container_width=True)
        st.markdown(
            '<div class="frame-caption">What a lovely picture! 💛</div>',
            unsafe_allow_html=True,
        )

    # --- Step 3: the magic button ----------------------------------------
    st.markdown('<div class="section-title">🪄 Ready for the magic?</div>', unsafe_allow_html=True)
    create_story = st.button("✨ Create my story! ✨")

    if create_story:
        reset_story()

        progress_placeholder = st.empty()
        progress_bar = st.progress(0)

        # Wake the models up (only the very first time).
        render_progress(progress_placeholder, progress_bar, "🌙", "Waking up the story elves...", 5)
        try:
            models = load_models()
        except Exception:
            progress_placeholder.empty()
            progress_bar.empty()
            render_message(
                "😴 The story elves are still sleeping. Please try again in a moment!",
                kind="note",
            )
            return

        # Stage 1 - look at the picture.
        render_progress(progress_placeholder, progress_bar, "👀", "Looking at your picture...", 25)
        try:
            caption = image2text(image, models["image"])
        except Exception:
            progress_placeholder.empty()
            progress_bar.empty()
            render_message(
                "🙈 I could not see that picture very well. Let's try another one!",
                kind="note",
            )
            return

        if not caption or not caption.strip():
            progress_placeholder.empty()
            progress_bar.empty()
            render_message(
                "🙈 That picture is a little too mysterious for me. Try another one!",
                kind="note",
            )
            return

        # Stage 2 - imagine the story.
        render_progress(progress_placeholder, progress_bar, "💭", "Imagining your adventure...", 55)
        try:
            story = text2story(caption, models["story"])
        except Exception:
            progress_placeholder.empty()
            progress_bar.empty()
            render_message(
                "💤 My imagination got sleepy. Please press the magic button again!",
                kind="note",
            )
            return

        if not story or not story.strip():
            progress_placeholder.empty()
            progress_bar.empty()
            render_message(
                "💤 My imagination got sleepy. Please press the magic button again!",
                kind="note",
            )
            return

        st.session_state["story"] = story

        # Stage 3 - read the story out loud.
        render_progress(progress_placeholder, progress_bar, "🎙️", "Giving your story a voice...", 80)
        try:
            audio, sampling_rate = text2audio(story, models["audio"])
            st.session_state["audio_bytes"] = audio_to_wav_bytes(audio, sampling_rate)
        except Exception:
            # The story is still perfectly readable without narration.
            st.session_state["audio_bytes"] = None

        render_progress(progress_placeholder, progress_bar, "🎉", "Your story is ready!", 100)
        progress_placeholder.empty()
        progress_bar.empty()

        st.balloons()

    # --- Step 4: show the finished story ---------------------------------
    if "story" in st.session_state:
        render_story(st.session_state["story"])

        audio_bytes = st.session_state.get("audio_bytes")
        if audio_bytes:
            render_audio(audio_bytes)
            st.download_button(
                "💾 Save my story audio",
                data=audio_bytes,
                file_name="my_story.wav",
                mime="audio/wav",
            )
        else:
            render_message("🤫 My voice is a little quiet today, but you can still read your story!")

        st.markdown(
            '<div class="section-title">🌈 Want another adventure?</div>',
            unsafe_allow_html=True,
        )
        if st.button("🔄 Make a new story"):
            reset_story()
            st.rerun()

    st.markdown(
        '<div class="footer-note">Made with ✨ for young storytellers</div>',
        unsafe_allow_html=True,
    )


if __name__ == "__main__":
    main()
