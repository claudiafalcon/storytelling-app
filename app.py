from transformers import pipeline

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

# The three models selected during the notebook experimentation stage.
IMAGE_MODEL = "Salesforce/blip-image-captioning-large"
STORY_MODEL = "LiquidAI/LFM2-1.2B"
AUDIO_MODEL = "facebook/mms-tts-eng"

# Limits used by the image and story stages.
MAX_CAPTION_TOKENS = 50
MAX_STORY_TOKENS = 180

ACCEPTED_IMAGE_TYPES = ["jpg", "jpeg", "png", "webp"]


# ---------------------------------------------------------------------------
# 1. Model loading
# ---------------------------------------------------------------------------

def get_hf_token():
    """
    Return the Hugging Face access token if one has been configured.

    The token is read from Streamlit secrets or from an environment variable,
    so it is never written inside the source code. The three models used by
    this application are public, so the token is optional.
    """
    try:
        token = st.secrets.get("HF_TOKEN")
        if token:
            return token
    except Exception:
        # No secrets file is configured, which is perfectly fine.
        pass

    return os.environ.get("HF_TOKEN")


@st.cache_resource(show_spinner=False)
def load_models():
    """
    Load the three Hugging Face pipelines used by the application.

    The @st.cache_resource decorator makes Streamlit load the models only
    once. Every later rerun of the script reuses the same pipelines instead
    of downloading and building them again.

    Returns a dictionary with the three ready-to-use pipelines.
    """
    token = get_hf_token()
    device = 0 if torch.cuda.is_available() else -1

    image_model = pipeline(
        "image-to-text",
        model=IMAGE_MODEL,
        token=token,
        device=device,
    )

    story_model = pipeline(
        "text-generation",
        model=STORY_MODEL,
        token=token,
        device=device,
    )

    audio_model = pipeline(
        "text-to-speech",
        model=AUDIO_MODEL,
        token=token,
        device=device,
    )

    return {
        "image": image_model,
        "story": story_model,
        "audio": audio_model,
    }


# ---------------------------------------------------------------------------
# 2. Image to text
# ---------------------------------------------------------------------------

def image2text(image, model):
    """
    Describe the content of an image.

    Parameters
    ----------
    image : PIL.Image.Image
        The picture uploaded by the child.
    model : transformers pipeline
        The image-to-text pipeline used to analyse the picture.

    Returns the caption generated by the model.
    """
    result = model(
        image,
        max_new_tokens=MAX_CAPTION_TOKENS
    )

    caption = result[0]["generated_text"]

    return caption


# ---------------------------------------------------------------------------
# 3. Text to story
# ---------------------------------------------------------------------------

def text2story(caption, model):
    """
    Create a short children's story from an image description.

    Parameters
    ----------
    caption : str
        The image description produced by the image-to-text model.
    model : transformers pipeline
        The text-generation pipeline used to write the story.

    Returns a story of approximately 50-100 words for children aged 3-10.
    """
    messages = [
        {
            "role": "system",
            "content": (
                "You are a children's storyteller for children aged 3 to 10. "
                "Write short, complete, child-friendly stories. "
                "Each story must have a beginning, a small adventure, "
                "a resolution, and a happy ending. "
                "Write approximately 60 to 80 words and never more than 100 words. "
                "Avoid violence, frightening events, and adult themes. "
                "Output only the story itself. "
                "Never output instructions, labels, headings, explanations, or formatting."
            )
        },
        {
            "role": "user",
            "content": (
                f"Create a short story inspired by this image description: {caption}"
            )
        }
    ]

    result = model(
        messages,
        max_new_tokens=MAX_STORY_TOKENS
    )

    story = result[0]["generated_text"][-1]["content"].strip()

    return story


# ---------------------------------------------------------------------------
# 4. Text to audio
# ---------------------------------------------------------------------------

def text2audio(text, model):
    """
    Turn the story into spoken audio.

    Parameters
    ----------
    text : str
        The story to narrate.
    model : transformers pipeline
        The text-to-speech pipeline used to read the story out loud.

    Returns a tuple (audio waveform, sampling rate).
    """
    result = model(text)

    audio = result["audio"]
    sampling_rate = result["sampling_rate"]

    return audio, sampling_rate


def audio_to_wav_bytes(audio, sampling_rate):
    """
    Convert the waveform produced by text2audio() into playable WAV bytes.

    Streamlit needs a real audio file to play and to download, so the raw
    waveform is normalised and written into an in-memory WAV file.
    """
    waveform = np.squeeze(np.asarray(audio, dtype=np.float32))

    peak = float(np.max(np.abs(waveform))) if waveform.size else 0.0
    if peak > 0:
        waveform = waveform / peak * 0.95

    samples = (waveform * 32767).astype(np.int16)

    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as wav_file:
        wav_file.setnchannels(1)
        wav_file.setsampwidth(2)
        wav_file.setframerate(int(sampling_rate))
        wav_file.writeframes(samples.tobytes())

    return buffer.getvalue()


