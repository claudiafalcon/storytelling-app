"""
Magic Story Maker
=================

An AI-powered storytelling application for children aged 3-10.

The child uploads a picture and the application:

    1. Looks at the picture          -> image2text()
    2. Imagines a story about it     -> text2story()
    3. Reads the story out loud      -> text2audio()

Everything is orchestrated by main() and presented through Streamlit.

Pre-trained models (Hugging Face Transformers pipelines):
    image-to-text   : Salesforce/blip-image-captioning-large
    text-generation : LiquidAI/LFM2-1.2B
    text-to-speech  : facebook/mms-tts-eng
"""

import html
